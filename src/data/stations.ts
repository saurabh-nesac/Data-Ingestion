export function getAlertForRainfall(rateMmPerHr: number): AlertThreshold {
  if (rateMmPerHr <= 0.1) return IMD_RAINFALL_THRESHOLDS[0];
  if (rateMmPerHr <= 7.5) return IMD_RAINFALL_THRESHOLDS[1];
  if (rateMmPerHr <= 35.5) return IMD_RAINFALL_THRESHOLDS[2];
  if (rateMmPerHr <= 64.4) return IMD_RAINFALL_THRESHOLDS[3];
  if (rateMmPerHr <= 124.4) return IMD_RAINFALL_THRESHOLDS[4];
  return IMD_RAINFALL_THRESHOLDS[5];
}
